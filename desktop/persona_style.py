_DEFAULT = _PERSONA_STYLE["温和沉稳"]


def available() -> list:
    """所有性格名（供设置下拉框使用）。"""
    return list(_PERSONA_STYLE)


def get(name: str) -> dict:
    return _PERSONA_STYLE.get((name or "").strip(), _DEFAULT)


def style_block(name: str) -> str:
    """生成注入 system 提示词的话术规格（让性格真的体现在嘴上）。"""
    s = get(name)
    samples = "\n".join("    · " + x for x in s["sample"])
    spice_line = ""
    if s.get("spice", 0) >= 1:
        spice_line = (
            "\n- 你可以偶尔冒一句接地气的口语（如："
            + "、".join(s["catch"][:4])
            + "），大约每 5~8 句出现一次，且只在感叹、惊讶、调侃时；"
            "**绝不能句句带**，正式场合和安慰人时一句都不许用。")
    return (
        f"【说话方式·{name}】（这条决定你「怎么说话」，必须体现）\n"
        f"- 语气：{s['tone']}\n"
        f"- 句式：{s['sentence']}\n"
        f"- 常用口头禅：{'、'.join(s['catch'][:6])}\n"
        f"- emoji：{s['emoji']}\n"
        f"- 禁忌：{s['taboo']}{spice_line}\n"
        f"- 照着这个味儿说（示范）：\n{samples}\n"
        f"（不要把上面这段复述给用户，也不要念参数；把它变成你说话的本能。）")


def voice_hint(name: str) -> dict:
    """语音参数倾向（语速/音高），交给 tts 叠加。"""
    return dict(get(name).get("voice") or {})


def spice_level(name: str) -> int:
    """市井口语允许度：0 不用 / 1 极少量 / 2 偶尔一句。"""
    return int(get(name).get("spice", 0))
